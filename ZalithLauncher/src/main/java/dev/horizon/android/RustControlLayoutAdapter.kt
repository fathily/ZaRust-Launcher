package dev.horizon.android

import android.content.Context
import android.util.Log
import com.movtery.zalithlauncher.game.control.ControlManager
import com.movtery.zalithlauncher.path.PathManager
import com.movtery.zalithlauncher.setting.AllSettings
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import kotlin.math.max
import kotlin.math.min

/**
 * Converts the currently selected Zalith LayerController layout to Starling's touch-layout.json.
 *
 * Starling owns the native game's input surface, so Zalith's Compose overlay cannot be drawn
 * directly over its NativeActivity. This adapter keeps the selected Zalith button positions and
 * key bindings, then writes the equivalent layout format consumed by Starling's touch engine.
 */
object RustControlLayoutAdapter {
    private const val TAG = "ZaRustControlAdapter"

    private val controlIds = listOf(
        "jump", "sneak", "inventory", "chat", "pause", "attack", "use",
        "drop", "offhand", "camera", "command", "debug", "pick", "players"
    )

    @JvmStatic
    fun apply(context: Context): Boolean {
        val root = RustEditionBridge.storageRoot(context)
        val sourceFile = File(root, "zarust-touch-layout.json")
        val activeFile = File(RustEditionBridge.gameHome(context), "touch-layout.json")
        if (RustEditionBridge.getInputMode(context) != "zalith") {
            if (sourceFile.exists() && !sourceFile.delete()) {
                Log.e(TAG, "Could not remove generated Zalith layout source: $sourceFile")
                return false
            }
            // Remove only a layout previously generated by ZaRust; preserve Starling's own layout.
            if (activeFile.isFile) {
                val isGenerated = runCatching {
                    JSONObject(activeFile.readText()).optString("zarustSource") == "zalith-control-manager"
                }.getOrDefault(false)
                if (isGenerated && !activeFile.delete()) {
                    Log.e(TAG, "Could not restore Starling's default touch layout")
                    return false
                }
            }
            return true
        }

        return try {
            val selectedFile = resolveSelectedLayout()
                ?: run {
                    Log.e(TAG, "No valid Zalith control layout was found; refusing to launch with Starling defaults")
                    return false
                }
            val source = JSONObject(selectedFile.readText())
            val layers = source.optJSONArray("layers") ?: JSONArray()
            val display = context.resources.displayMetrics
            val minSide = min(display.widthPixels, display.heightPixels).coerceAtLeast(1)
            val resultButtons = JSONObject()
            val mapped = HashSet<String>()
            val movementButtons = linkedMapOf<String, JSONObject>()
            var joystick: JSONObject? = null

            for (index in 0 until layers.length()) {
                val layer = layers.optJSONObject(index) ?: continue
                if (layer.optBoolean("hide", false)) continue
                val layerName = layer.optString("name").lowercase()
                if (layerName == "gui") continue

                val joysticks = layer.optJSONArray("joystickButtons") ?: JSONArray()
                if (joystick == null && joysticks.length() > 0) {
                    joystick = joysticks.optJSONObject(0)
                }

                val buttons = layer.optJSONArray("normalButtons") ?: JSONArray()
                for (buttonIndex in 0 until buttons.length()) {
                    val button = buttons.optJSONObject(buttonIndex) ?: continue
                    val events = button.optJSONArray("clickEvents") ?: JSONArray()
                    val keys = (0 until events.length()).mapNotNull { eventIndex ->
                        events.optJSONObject(eventIndex)
                            ?.takeIf { it.optString("type") == "key" }
                            ?.optString("key")
                            ?.uppercase()
                    }
                    if (keys.isEmpty()) continue

                    keys.mapNotNull { MOVEMENT_KEY_ALIASES[it] }
                        .forEach { direction -> movementButtons.putIfAbsent(direction, button) }

                    val targetId = actionFor(keys) ?: continue
                    if (targetId in mapped) continue
                    val position = button.optJSONObject("position") ?: continue
                    resultButtons.put(
                        targetId,
                        place(
                            x = position.optInt("x", 5000) / 10000.0,
                            y = position.optInt("y", 5000) / 10000.0,
                            size = buttonRadius(button.optJSONObject("buttonSize"), minSide, display.widthPixels, display.heightPixels, display.density),
                            show = "on"
                        )
                    )
                    mapped.add(targetId)
                }
            }

            var movement = "auto"
            val stick = when {
                joystick != null -> {
                    movement = "analog"
                    val position = joystick!!.optJSONObject("position") ?: JSONObject()
                    val stickSize = if (joystick!!.optString("sizeType") == "dp") {
                        val diameterPx = joystick!!.optDouble("sizeDp", 200.0) * display.density
                        4.5 * diameterPx / minSide
                    } else {
                        4.5 * (joystick!!.optInt("sizePercentage", 2500) / 10000.0)
                    }
                    place(
                        position.optInt("x", 1200) / 10000.0,
                        position.optInt("y", 7330) / 10000.0,
                        stickSize.coerceIn(0.3, 2.5),
                        "on"
                    )
                }
                movementButtons.keys.containsAll(CARDINAL_DIRECTIONS) -> {
                    movement = "dpad"
                    val positions = CARDINAL_DIRECTIONS.mapNotNull { direction ->
                        movementButtons[direction]?.optJSONObject("position")
                    }
                    val x = positions.map { it.optInt("x", 5000) }.average() / 10000.0
                    val y = positions.map { it.optInt("y", 5000) }.average() / 10000.0
                    val buttonSize = movementButtons.values.firstOrNull()?.optJSONObject("buttonSize")
                    place(
                        x, y,
                        (buttonRadius(buttonSize, minSide, display.widthPixels, display.heightPixels, display.density) * 1.8).coerceIn(0.5, 2.5),
                        "on"
                    )
                }
                else -> {
                    error("The selected ZaRust layout has no joystick or complete up/down/left/right movement controls. Starling defaults will not be enabled.")
                }
            }

            require(mapped.isNotEmpty()) {
                "The selected ZaRust layout contains no supported Rust game actions."
            }

            // The native engine uses this layout file for its on-screen input surface.
            // Every control absent from the selected ZaRust layout is explicitly disabled;
            // it must never inherit Starling's default button placement.
            for (id in controlIds) {
                if (!resultButtons.has(id)) {
                    resultButtons.put(id, place(0.5, 0.5, 0.6, "off"))
                }
            }

            val output = JSONObject()
                .put("version", 2)
                .put("zarustSource", "zalith-control-manager")
                .put("opacity", 1.0)
                .put("movement", movement)
                .put("sneak", "toggle")
                .put("interact", "tap")
                .put("anchor", "floating")
                .put("vibrate", true)
                .put("gyro", false)
                .put("stick", stick)
                .put("buttons", resultButtons)
                .put("mods", JSONObject())

            val temporary = File(root, sourceFile.name + ".partial")
            temporary.writeText(output.toString(2))
            if (sourceFile.exists() && !sourceFile.delete()) {
                temporary.delete()
                error("Could not replace generated Zalith layout source")
            }
            check(temporary.renameTo(sourceFile)) { "Could not commit generated Zalith layout source" }
            Log.i(
                TAG,
                "Prepared ZaRust control layout ${selectedFile.name}; movement=$movement, " +
                    "mapped=${mapped.size}, source=$sourceFile. The Rust engine will apply it " +
                    "after its game-folder migration; all unmapped built-in buttons are disabled."
            )
            true
        } catch (error: Exception) {
            Log.e(TAG, "Could not convert Zalith control layout", error)
            false
        }
    }


    /**
     * ControlManager loads its StateFlow asynchronously on Activity.onResume. On a fast first
     * launch the flow can still be null, so resolve the persisted selection directly from the
     * same layout directory instead of silently falling back to Starling's built-in controls.
     */
    private fun resolveSelectedLayout(): File? {
        ControlManager.selectedLayout.value?.file
            ?.takeIf { it.isFile }
            ?.let { return it }

        val directory = runCatching { PathManager.DIR_CONTROL_LAYOUTS }.getOrNull()
            ?: return null
        val files = directory.listFiles()
            ?.filter { it.isFile && it.extension.equals("json", ignoreCase = true) }
            .orEmpty()

        val selectedName = runCatching { AllSettings.controlLayout.getValue() }
            .getOrNull()
            .orEmpty()
        if (selectedName.isNotBlank()) {
            return files.firstOrNull {
                it.name == selectedName ||
                    it.nameWithoutExtension == selectedName ||
                    it.absolutePath == selectedName
            }
        }

        // On a clean install the launcher may not have persisted a selection yet.
        // Only then use a file explicitly marked as the layout's default.
        return files.firstOrNull { file ->
            runCatching {
                JSONObject(file.readText())
                    .optJSONObject("info")
                    ?.optJSONObject("name")
                    ?.optString("default")
                    ?.isNotBlank() == true
            }.getOrDefault(false)
        }
    }

    private fun actionFor(keys: List<String>): String? {
        if (keys.any { it.contains("MOUSE_BUTTON_LEFT") }) return "attack"
        if (keys.any { it.contains("MOUSE_BUTTON_RIGHT") }) return "use"
        if (keys.any { it.contains("MOUSE_BUTTON_MIDDLE") }) return "pick"
        return when {
            keys.any { it.endsWith("KEY_SPACE") } -> "jump"
            keys.any { it.contains("LEFT_SHIFT") || it.contains("RIGHT_SHIFT") } -> "sneak"
            keys.any { it.endsWith("KEY_ESCAPE") } -> "pause"
            keys.any { it.endsWith("KEY_E") } -> "inventory"
            keys.any { it.endsWith("KEY_T") } -> "chat"
            keys.any { it.endsWith("KEY_F3") } -> "debug"
            keys.any { it.endsWith("KEY_F5") } -> "camera"
            keys.any { it.endsWith("KEY_Q") } -> "drop"
            keys.any { it.endsWith("KEY_F") } -> "offhand"
            keys.any { it.endsWith("KEY_SLASH") } -> "command"
            keys.any { it.endsWith("KEY_TAB") } -> "players"
            else -> null
        }
    }

    private fun buttonRadius(
        size: JSONObject?,
        minSide: Int,
        screenWidth: Int,
        screenHeight: Int,
        density: Float
    ): Double {
        if (size == null) return 0.65
        val widthPercent = size.optInt("widthPercentage", 1200) / 10000.0
        val heightPercent = size.optInt("heightPercentage", 1200) / 10000.0
        val widthReference = if (size.optString("widthReference") == "screen_width") screenWidth else screenHeight
        val heightReference = if (size.optString("heightReference") == "screen_width") screenWidth else screenHeight
        val percentageDiameter = max(widthPercent * widthReference, heightPercent * heightReference)
        val diameterPx = if (size.optString("type") == "dp") {
            max(size.optDouble("widthDp", 50.0), size.optDouble("heightDp", 50.0)) * density
        } else {
            percentageDiameter
        }
        return (4.5 * diameterPx / minSide).coerceIn(0.3, 2.5)
    }

    private fun place(x: Double, y: Double, size: Double, show: String): JSONObject =
        JSONObject()
            .put("x", x.coerceIn(0.0, 1.0))
            .put("y", y.coerceIn(0.0, 1.0))
            .put("size", size.coerceIn(0.3, 2.5))
            .put("show", show)
            .put("opacity", 1.0)

    private val CARDINAL_DIRECTIONS = setOf("up", "down", "left", "right")

    private val MOVEMENT_KEY_ALIASES = mapOf(
        "GLFW_KEY_W" to "up",
        "GLFW_KEY_UP" to "up",
        "GLFW_KEY_S" to "down",
        "GLFW_KEY_DOWN" to "down",
        "GLFW_KEY_A" to "left",
        "GLFW_KEY_LEFT" to "left",
        "GLFW_KEY_D" to "right",
        "GLFW_KEY_RIGHT" to "right"
    )
}
